from io import StringIO

import pytest
from django.contrib.auth.models import User
from django.core.management import CommandError, call_command
from django.db.models.signals import post_save
from django.test import override_settings

from tests.testapp.models import Order, Tag


def run(*args):
    out, err = StringIO(), StringIO()
    call_command("signal_map", *args, stdout=out, stderr=err)
    return out.getvalue(), err.getvalue()


def new_receiver(sender, **kwargs):
    pass


def test_readable_map_lists_first_party_receivers():
    out, _ = run()
    assert "First-party receivers (5)" in out
    assert "tests.testapp.signals.reindex_order  (tests/testapp/signals.py:" in out
    assert "django.contrib.auth" not in out  # Django internals need --all


def test_all_includes_django_internals():
    out, _ = run("--all")
    assert "django.db.close_old_connections" in out


def test_signal_is_named_after_the_module_defining_it():
    # order_paid is defined in testapp/events.py and imported in signals.py.
    out, _ = run()
    assert "tests.testapp.events.order_paid" in out
    assert "tests.testapp.signals.order_paid" not in out


def test_lock_file_format(tmp_path):
    lock = tmp_path / "signals.lock"
    run("--write", "--lock-file", str(lock))
    text = lock.read_text()
    assert text.startswith("# signals.lock: generated by")
    body = text.split("[first-party]\n", 1)[1].split("\n\n[third-party]")[0]
    assert body.splitlines() == [
        "django.db.models.signals.post_save | testapp.Event | "
        "tests.testapp.signals.track_event",
        "django.db.models.signals.post_save | testapp.Note | "
        "tests.testapp.signals.warm_note_cache",
        "django.db.models.signals.post_save | testapp.Order | "
        "tests.testapp.signals.reindex_order",
        "django.db.models.signals.pre_save | testapp.Order | "
        "tests.testapp.signals.normalize_status",
        "tests.testapp.events.order_paid | * | "
        "tests.testapp.signals.send_receipt | uid=send-receipt",
    ]
    assert ".py:" not in text  # no line numbers, so edits do not churn it


def test_check_passes_when_up_to_date(tmp_path):
    lock = tmp_path / "signals.lock"
    run("--write", "--lock-file", str(lock))
    out, _ = run("--check", "--lock-file", str(lock))
    assert out.strip() == "signals.lock is up to date (5 receivers)."


def test_check_fails_with_diff_when_a_receiver_is_added(tmp_path):
    lock = tmp_path / "signals.lock"
    run("--write", "--lock-file", str(lock))
    post_save.connect(new_receiver, sender=Tag)
    try:
        err = StringIO()
        with pytest.raises(CommandError, match="out of date"):
            call_command("signal_map", "--check", "--lock-file", str(lock), stderr=err)
        assert (
            "+django.db.models.signals.post_save | testapp.Tag | "
            "tests.test_signal_map.new_receiver"
        ) in err.getvalue()
    finally:
        post_save.disconnect(new_receiver, sender=Tag)


def test_check_fails_when_lock_file_is_missing(tmp_path):
    with pytest.raises(CommandError, match="does not exist"):
        run("--check", "--lock-file", str(tmp_path / "missing.lock"))


def test_lock_file_setting_is_relative_to_base_dir(tmp_path):
    with override_settings(BASE_DIR=tmp_path, SIGNAL_GUARD={"LOCK_FILE": "x.lock"}):
        run("--write")
    assert (tmp_path / "x.lock").exists()


@override_settings(SIGNAL_GUARD={"FIRST_PARTY": ["tests.testapp"]})
def test_third_party_receivers_on_your_models_are_mapped(tmp_path):
    # With FIRST_PARTY set, this test module counts as third-party code.
    post_save.connect(new_receiver, sender=Order)
    post_save.connect(new_receiver, sender=User)
    try:
        lock = tmp_path / "signals.lock"
        run("--write", "--lock-file", str(lock))
        third_party = lock.read_text().split("[third-party]\n", 1)[1]
        assert third_party.splitlines() == [
            "django.db.models.signals.post_save | testapp.Order | "
            "tests.test_signal_map.new_receiver"
        ]
    finally:
        post_save.disconnect(new_receiver, sender=Order)
        post_save.disconnect(new_receiver, sender=User)
